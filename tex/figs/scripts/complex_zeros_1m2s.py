import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
sig = np.linspace(-2, 2, 401)
t = np.linspace(-25, 25, 801)
SG, TT = np.meshgrid(sig, t)
F = np.abs(1 - 2.0 ** (-(SG + 1j * TT)))
fig, ax = plt.subplots(figsize=(6, 4))
cs = ax.contourf(SG, TT, np.log10(F + 1e-6), levels=30, cmap="viridis")
fig.colorbar(cs, ax=ax, label=r"$\log_{10}|1-2^{-s}|$")
ks = np.arange(-2, 3)
ax.plot(np.zeros_like(ks), 2 * np.pi * ks / np.log(2), "r*", ms=12, label="zeros")
ax.axvline(0.5, color="w", ls="--", label=r"critical line $\sigma=1/2$")
ax.set_xlabel(r"$\sigma=\mathrm{Re}\,s$ (dimensionless)"); ax.set_ylabel(r"$t=\mathrm{Im}\,s$ (dimensionless)")
ax.legend(fontsize=7, loc="upper right")
plt.savefig("complex_zeros_1m2s.pdf", bbox_inches="tight")
