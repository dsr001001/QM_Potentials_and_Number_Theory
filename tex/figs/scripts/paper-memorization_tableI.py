import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
ins = np.array([0.212,0.120,0.128,0.226,0.137,0.142,0.206,0.064,0.147,0.242,0.170,0.103])
oos = np.array([0.317,0.320,0.273,0.274,0.369,0.271,0.265,0.313,0.439,0.370,0.279,0.302])
cor = np.array([-0.01,-0.17,0.04,-0.09,-0.07,-0.16,-0.14,-0.16,0.12,-0.01,-0.03,0.08])
sc = np.array([1]*9 + [2]*3)
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
a1.axhspan(0.261, 0.274, color='0.85', label='null range')
a1.plot(ins[sc == 1], oos[sc == 1], 'o', label='scale 1')
a1.plot(ins[sc == 2], oos[sc == 2], 's', label='scale 2')
a1.set_xlabel('in-sample rms (mean spacings)')
a1.set_ylabel('OOS rms (mean spacings)')
a1.legend(fontsize=7)
idx = np.arange(1, 13)
a2.bar(idx, cor, color=['C0']*9 + ['C1']*3)
a2.axhline(0.96, ls='--', color='k', label='six-prime oracle')
a2.axhline(0.0, color='k', lw=0.5)
a2.set_xlabel('Table I row (table order)')
a2.set_ylabel('OOS correlation (dimensionless)')
a2.set_ylim(-0.3, 1.05)
a2.legend(fontsize=7)
plt.tight_layout()
plt.savefig('paper-memorization_tableI.pdf', bbox_inches='tight')
