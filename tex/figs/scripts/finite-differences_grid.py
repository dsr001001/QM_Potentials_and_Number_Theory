import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
N = 7; L = 1.0; h = 2*L/(N+1)
xall = -L + h*np.arange(N+2)
xi = xall[1:-1]
psi = np.cos(np.pi*xi/(2*L))
xf = np.linspace(-L, L, 400)
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
a1.plot(xf, np.cos(np.pi*xf/(2*L)), color='0.6', lw=1, label='continuum ground state')
a1.plot(xi, psi, 'o', color='C0', label='interior unknowns')
a1.plot([-L, L], [0, 0], 's', mfc='white', mec='k', ms=8, label='wall points')
a1.axhline(0, color='k', lw=0.5)
for xv in xall:
    a1.axvline(xv, color='0.85', lw=0.5, zorder=0)
a1.set_xlabel('x (dimensionless)')
a1.set_ylabel(r'$\psi$ (arbitrary units)')
a1.set_ylim(-0.6, 1.15)
a1.legend(fontsize=6, loc='lower center')
H = (np.diag(2/h**2*np.ones(N)) + np.diag(-np.ones(N-1)/h**2, 1)
     + np.diag(-np.ones(N-1)/h**2, -1))
a2.imshow(np.where(H != 0, 1, 0), cmap='Greys', vmin=0, vmax=1.3)
a2.set_xticks(range(N)); a2.set_xticklabels(range(1, N+1))
a2.set_yticks(range(N)); a2.set_yticklabels(range(1, N+1))
a2.set_xlabel('column index'); a2.set_ylabel('row index')
a2.set_title(r'nonzero entries of $\mathsf{H}$ ($7\times7$)', fontsize=9)
plt.tight_layout()
plt.savefig('finite-differences_grid.pdf', bbox_inches='tight')
