import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
n = np.arange(1, 41)
k = n.astype(float)
geo = np.cumsum(2.0**-(k - 1))
p2 = np.cumsum(1/k**2)
alt = np.cumsum((-1.0)**(n + 1)/k)
har = np.cumsum(1/k)
fig, ax = plt.subplots(figsize=(6, 4))
for y in [2.0, np.pi**2/6, np.log(2)]:
    ax.axhline(y, color='gray', lw=0.8)
ax.plot(n, geo, 'o-', ms=3, lw=0.8, label=r'$\sum 2^{-(k-1)}\to 2$')
ax.plot(n, p2, 's-', ms=3, lw=0.8, label=r'$\sum 1/k^2\to\pi^2/6$')
ax.plot(n, alt, '^-', ms=3, lw=0.8, label=r'$\sum (-1)^{k+1}/k\to\log 2$')
ax.plot(n, har, 'd-', ms=3, lw=0.8, label=r'$\sum 1/k$ (diverges)')
ax.plot(n, np.log(k) + 0.5772156649, 'k--', lw=0.8, label=r'$\log n+\gamma$')
ax.set_xlabel('number of terms $n$ (dimensionless)')
ax.set_ylabel('partial sum $S_n$ (dimensionless)')
ax.legend(fontsize=8, loc='upper left')
plt.savefig("series_partialsums.pdf", bbox_inches="tight")
