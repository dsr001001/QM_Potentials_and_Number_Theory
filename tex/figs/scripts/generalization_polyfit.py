import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
rng = np.random.default_rng(2)
t_tr = np.linspace(0, 2*np.pi, 10)
y_tr = np.sin(t_tr) + 0.15*rng.standard_normal(10)
tt = np.linspace(0, 2.4*np.pi, 600)
fig, ax = plt.subplots(figsize=(6, 4))
ax.axvspan(2*np.pi, 2.4*np.pi, color="0.9", label="extrapolation")
ax.plot(tt, np.sin(tt), "k--", label=r"$\sin t$")
for deg, st in [(1, "-"), (3, "-."), (9, "-")]:
    p = np.polynomial.Polynomial.fit(t_tr, y_tr, deg)
    ax.plot(tt, p(tt), st, lw=1.5 if deg == 9 else 1.0, label=f"degree {deg}")
ax.plot(t_tr, y_tr, "ko", ms=5, label="training data")
ax.set_ylim(-2.5, 2.5)
ax.set_xlabel(r"$t$ (dimensionless)"); ax.set_ylabel(r"$y$ (dimensionless)")
ax.legend(fontsize=8, loc="lower left")
plt.savefig("generalization_polyfit.pdf", bbox_inches="tight")
