import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
k = 2.0
x = np.linspace(0, 2*np.pi, 500)
a1.plot(x, np.cos(k*x), "-", label="Re")
a1.plot(x, np.sin(k*x), "--", label="Im")
a1.plot(x, np.ones_like(x), ":", label="modulus")
a1.set_xlabel("x (units with hbar = 2m = 1)")
a1.set_ylabel("e^{ikx}, k = 2")
a1.legend(fontsize=7, loc="lower left")
kk = np.linspace(0, 3, 300)
a2.plot(kk, 2*kk, label="string: omega = v k, v = 2")
a2.plot(kk, kk**2, "--", label="matter wave: omega = k^2")
a2.set_xlabel("wavenumber k")
a2.set_ylabel("angular frequency omega")
a2.legend(fontsize=7)
plt.tight_layout()
plt.savefig("schrodinger_planewave.pdf", bbox_inches="tight")
