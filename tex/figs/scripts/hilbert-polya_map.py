import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
t = np.array([14.134725, 21.022040, 25.010858, 30.424876, 32.935062,
              37.586178, 40.918719, 43.327073, 48.005151, 49.773832])
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
a1.axvspan(0, 1, color="0.9", label="critical strip")
a1.axvline(0.5, ls="--", color="k", lw=0.8)
a1.plot(0.5*np.ones_like(t), t, "o", color="C0", ms=4, label="zeros (RE1)")
a1.plot([0.6], [20.0], "x", color="C3", ms=8, mew=2, label="hypothetical $0.6+20i$")
a1.set_xlim(-0.5, 1.5); a1.set_ylim(0, 55)
a1.set_xlabel(r"$\mathrm{Re}\,s$ (dimensionless)")
a1.set_ylabel(r"$\mathrm{Im}\,s$ (dimensionless)")
a1.legend(fontsize=7, loc="lower right")
a1.set_title(r"$s$-plane", fontsize=9)
a2.axhline(0, color="k", lw=0.8)
a2.plot(t, np.zeros_like(t), "o", color="C0", ms=4)
a2.plot([20.0], [-0.1], "x", color="C3", ms=8, mew=2)
a2.annotate(r"$t=20-0.1i$", (20, -0.1), (24, -0.4), fontsize=8,
            arrowprops=dict(arrowstyle="->", lw=0.8))
a2.set_xlim(0, 55); a2.set_ylim(-0.6, 0.6)
a2.set_xlabel(r"$\mathrm{Re}\,t$ (dimensionless)")
a2.set_ylabel(r"$\mathrm{Im}\,t$ (dimensionless)")
a2.set_title(r"$t=-i(\rho-1/2)$", fontsize=9)
plt.tight_layout()
plt.savefig("hilbert-polya_map.pdf", bbox_inches="tight")
