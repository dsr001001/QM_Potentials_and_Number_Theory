import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
import qmnt
n = np.arange(370, 461)
t = np.asarray(qmnt.zeros(460))
true = np.asarray(qmnt.fluct(t[n-1], n))
pred = np.asarray(qmnt.oracle_zeros(n, qmnt.first_primes(6)))
pf = np.asarray(qmnt.fluct(pred, n))
fig, ax = plt.subplots(figsize=(6, 4))
ax.axvspan(400.5, 460.5, color='0.85', label='held out')
ax.plot(n, true, 'ko', ms=3, label='true fluctuation')
ax.plot(n, pf, color='tab:blue', label='six-prime formula')
ax.set_xlabel('zero index $n$')
ax.set_ylabel('fluctuation (mean spacings)')
ax.legend(loc='upper left', fontsize=8)
plt.savefig('intro_trainhold.pdf', bbox_inches='tight')
