import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
t = np.linspace(0, 10, 4000)
j = np.arange(0, 11)
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(t, np.cos(0.5*t), label='cos(0.5 t)')
ax.plot(t, np.cos((2*np.pi-0.5)*t), lw=0.8, label='cos(5.783 t)')
ax.plot(j, np.cos(0.5*j), 'ko', label='samples at integer t')
ax.set_xlabel('t (dimensionless)'); ax.set_ylabel('value')
ax.legend(fontsize=8, loc='lower left')
plt.savefig("fourier-transform_aliasing.pdf", bbox_inches="tight")
