import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(6.5, 3))
x = np.linspace(-0.5, 4.5, 100)
for ax in (ax1, ax2):
    ax.plot(x, 3 - x, label="x+y=3")
    ax.plot(x, x - 1, label="x-y=1")
    ax.set_xlim(-0.5, 4.5); ax.set_ylim(-1, 4)
    ax.set_xlabel("x (dimensionless)")
ax1.plot([2], [1], "ko")
ax1.set_ylabel("y (dimensionless)"); ax1.set_title("unique solution")
ax2.plot(x, (5 - x)/2, label="x+2y=5")
ax2.set_title("overdetermined: no common point")
ax1.legend(fontsize=7); ax2.legend(fontsize=7)
plt.tight_layout()
plt.savefig("linear-algebra_lines.pdf", bbox_inches="tight")
