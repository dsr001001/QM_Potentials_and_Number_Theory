import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
import qmnt
t = qmnt.zeros(40)
t = t[t <= 100]
tt = np.linspace(10, 100, 4000)
N = np.searchsorted(t, tt, side="right")
u = qmnt.Nsm(tt)
fig, ax = plt.subplots(1, 2, figsize=(6.5, 3))
ax[0].plot(tt, N, drawstyle="steps-post", label="N(t)")
ax[0].plot(tt, u, label=r"$N_{\rm sm}(t)$")
ax[0].set_xlabel("height t (dimensionless)")
ax[0].set_ylabel("number of zeros")
ax[0].set_title("(a)")
ax[0].legend(fontsize=8)
ax[1].plot(u, N, drawstyle="steps-post", label="N against u")
ax[1].plot(u, u, "--", label="N = u")
ax[1].set_xlabel(r"unfolded variable $u=N_{\rm sm}(t)$")
ax[1].set_ylabel("number of zeros")
ax[1].set_title("(b)")
ax[1].legend(fontsize=8)
plt.tight_layout()
plt.savefig("level-statistics_staircase.pdf", bbox_inches="tight")
