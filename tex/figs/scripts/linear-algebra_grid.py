import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
N = 15; h = 2/(N+1)
xj = -1 + h*np.arange(1, N+1)
f = lambda x: np.sin(3*np.pi*(x+1)/2)
xx = np.linspace(-1, 1, 400)
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(xx, f(xx), "k-", lw=1, label="f(x)")
ax.stem(xj, f(xj), linefmt="C0-", markerfmt="C0o", basefmt="k:", label="stored values f(x_j)")
ax.axvline(-1, color="gray"); ax.axvline(1, color="gray")
ax.set_xlabel("x (dimensionless)"); ax.set_ylabel("f (dimensionless)")
ax.legend(fontsize=8)
plt.savefig("linear-algebra_grid.pdf", bbox_inches="tight")
