import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
def shifts(K):
    k = np.arange(1, K+1); kk, ll = np.meshgrid(k, k, indexing='ij')
    A = -0.5*((abs(kk-ll)==2).astype(float)-(kk+ll==2).astype(float))
    E = k**2.0; D = E[:,None]-E[None,:]; np.fill_diagonal(D, np.inf)
    return k, -(A**2/D).sum(axis=1)
k4, s4 = shifts(400); k3, s3 = shifts(30)
fig, ax = plt.subplots(figsize=(6,4))
ax.plot(k4[:30], k4[:30]**2*s4[:30], 'o', mfc='none', label='400-state basis')
ax.plot(k3, k3**2*s3, 's', ms=4, label='30-state basis')
ax.axhline(0, color='gray', lw=0.5)
ax.set_xlabel('level index $n$')
ax.set_ylabel(r'$n^2\,\delta E_n$ (units where $E_k=k^2$)')
ax.legend()
plt.savefig('paper-spurious-floor_truncation.pdf', bbox_inches='tight')
