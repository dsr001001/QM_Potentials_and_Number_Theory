import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
x=np.linspace(-4,4,2000); V=x**2; E=9.0
fig,ax=plt.subplots(figsize=(6,4))
ax.plot(x,V,'k-',label='$V(x)=x^2$')
ax.axhline(E,color='gray',lw=1)
ax.axvspan(-4,-3,color='0.85'); ax.axvspan(3,4,color='0.85')
xi=np.linspace(-2.9,2.9,3000); k=np.sqrt(E-xi**2)
th=np.concatenate([[0],np.cumsum(0.5*(k[1:]+k[:-1])*np.diff(xi))])
psi=E+1.6*np.cos(th*2.0)/np.sqrt(k)
ax.plot(xi,psi,'b-',lw=1,label='sketched wave')
ax.text(-3,E+0.6,'$x_1$',ha='center'); ax.text(3,E+0.6,'$x_2$',ha='center')
ax.plot([-3,3],[E,E],'ko',ms=4)
ax.text(-3.9,1,'forbidden',fontsize=8); ax.text(3.05,1,'forbidden',fontsize=8)
ax.set_xlim(-4,4); ax.set_ylim(0,16)
ax.set_xlabel('$x$ (units $\\hbar=2m=1$)'); ax.set_ylabel('energy $V$, $E$')
ax.legend(loc='upper center',fontsize=8)
plt.savefig("wkb_turning.pdf", bbox_inches="tight")
