import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, ax = plt.subplots(1, 2, figsize=(6.5, 3))
t = np.linspace(0, 3000, 3001); tc = 347
for dwv, ls in [(3e-4, "-"), (1e-3, "--"), (3e-3, ":")]:
    ax[0].plot(t, np.cos(dwv*(t - tc)), ls, lw=1, label=r"$\delta\omega=%g$" % dwv)
ax[0].axvspan(14, 680, color="0.85")
ax[0].axhline(0, color="0.6", lw=0.5)
ax[0].set_xlabel(r"height $t$ (dimensionless)")
ax[0].set_ylabel(r"local correlation $\cos\epsilon$")
ax[0].set_title("(a)", fontsize=9)
ax[0].legend(fontsize=7, loc="lower left")
eps = np.linspace(0, np.pi, 400)
ax[1].plot(eps, 2*np.abs(np.sin(eps/2)), label=r"rms ratio $2|\sin(\epsilon/2)|$")
ax[1].plot(eps, np.cos(eps), "--", label=r"corr $\cos\epsilon$")
ax[1].axvline(np.pi/3, ls=":", color="gray")
ax[1].axhline(1, color="0.6", lw=0.5)
ax[1].set_xlabel(r"phase error $\epsilon$ (rad)")
ax[1].set_ylabel("ratio or correlation")
ax[1].set_title("(b)", fontsize=9)
ax[1].legend(fontsize=7, loc="lower left")
plt.tight_layout()
plt.savefig("sparse-frequency_dephasing.pdf", bbox_inches="tight")
