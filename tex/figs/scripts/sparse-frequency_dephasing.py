import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, ax = plt.subplots(1, 2, figsize=(6.5, 3))
tc = 347.0
tt = np.linspace(0, 6000, 3000)
for dw in (3e-4, 1e-3, 3e-3):
    ax[0].plot(tt, np.cos(dw*(tt - tc)), label=r"$\delta\omega=%g$" % dw)
ax[0].axvspan(14, 680, color="gray", alpha=0.3)
ax[0].set_xlabel(r"height $t$ (dimensionless)")
ax[0].set_ylabel(r"local correlation $\cos\phi$")
ax[0].set_title("(a)", fontsize=9)
ax[0].legend(fontsize=7)
phi = np.linspace(0, np.pi, 400)
ax[1].plot(phi, 2*np.abs(np.sin(phi/2)), label="rms / null rms")
ax[1].plot(phi, np.cos(phi), label=r"corr $=\cos\phi$")
ax[1].axvline(np.pi/3, ls=":", color="k")
ax[1].axhline(1, ls=":", color="gray", lw=0.7)
ax[1].set_xlabel(r"phase error $\phi$ (rad)")
ax[1].set_title("(b)", fontsize=9)
ax[1].legend(fontsize=7)
plt.tight_layout()
plt.savefig("sparse-frequency_dephasing.pdf", bbox_inches="tight")
