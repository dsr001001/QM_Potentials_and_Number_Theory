import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
import qmnt
L = 44.883
x = np.linspace(0.0, L, 300)
V = np.array([qmnt.wu_sprung_V(xi) for xi in x])
t = qmnt.zeros(500)
xt = np.array([qmnt.wu_sprung_x(ti) for ti in t])
n = np.arange(1, 501)
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
a1.plot(x, V, color='C0')
a1.axvspan(22.5, 28.5, color='0.85')
a1.plot([26.82], [500.0], 'ko')
a1.set_xlabel('$x$ (units $\\hbar=2m=1$)')
a1.set_ylabel('$V(x)$ (energy units)')
a2.plot(n, xt, color='C1')
a2.axvspan(201, 300, color='0.85')
a2.set_xlabel('level index $n$')
a2.set_ylabel('turning point $x(t_n)$')
plt.tight_layout()
plt.savefig('paper-memorization_turning.pdf', bbox_inches='tight')
