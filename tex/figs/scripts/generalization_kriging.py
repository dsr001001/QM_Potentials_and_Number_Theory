import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
r = np.linspace(-0.7, 0.7, 281)
cn = np.sqrt(2)*r
ck = np.sqrt(2)*np.abs(r)
en = np.sqrt(0.5 - 2*r + 1)
ek = np.sqrt(1 - 2*r**2)
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
a1.plot(r, cn, "r-", label="neighbor mean"); a1.plot(r, ck, "b--", label="kriging")
a1.axvline(-0.29, ls=":", color="k"); a1.axhline(0, color="0.6", lw=0.5)
a1.set_xlabel(r"$\rho_1$"); a1.set_ylabel("correlation with truth"); a1.legend(fontsize=7)
a2.plot(r, en, "r-", label="neighbor mean"); a2.plot(r, ek, "b--", label="kriging")
a2.axhline(1, ls=":", color="k"); a2.axvline(-0.29, ls=":", color="k")
a2.set_xlabel(r"$\rho_1$"); a2.set_ylabel("rms / null rms"); a2.legend(fontsize=7)
plt.tight_layout()
plt.savefig("generalization_kriging.pdf", bbox_inches="tight")
