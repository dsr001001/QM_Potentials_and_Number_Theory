import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
rng = np.random.default_rng(3)
t_tr = np.linspace(0, 2*np.pi, 15)
y_tr = np.sin(t_tr) + 0.15*rng.standard_normal(15)
t_in = rng.uniform(0, 2*np.pi, 200)
t_out = np.linspace(2*np.pi, 2.4*np.pi, 50)
y_in = np.sin(t_in) + 0.15*rng.standard_normal(200)
y_out = np.sin(t_out) + 0.15*rng.standard_normal(50)
rms = lambda e: np.sqrt(np.mean(e**2))
degs = np.arange(15); Ei = []; Eo1 = []; Eo2 = []
for deg in degs:
    p = np.polynomial.Polynomial.fit(t_tr, y_tr, deg)
    Ei.append(max(rms(p(t_tr)-y_tr), 1e-16)); Eo1.append(rms(p(t_in)-y_in)); Eo2.append(rms(p(t_out)-y_out))
fig, ax = plt.subplots(figsize=(6, 4))
ax.semilogy(degs, Ei, "o-", label="in-sample")
ax.semilogy(degs, Eo1, "s-", label="out-of-sample, interpolation")
ax.semilogy(degs, Eo2, "^-", label="out-of-sample, extrapolation")
ax.axhline(0.15, ls=":", color="k", label="noise level")
ax.set_xlabel("polynomial degree"); ax.set_ylabel("rms error (dimensionless)")
ax.legend(fontsize=8)
plt.savefig("generalization_errorcurve.pdf", bbox_inches="tight")
