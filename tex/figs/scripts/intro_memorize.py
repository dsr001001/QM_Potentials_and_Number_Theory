import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
x = np.array([0, 1, 2, 3, 4.0]); y = np.array([1.0, 2.9, 5.2, 6.9, 9.1])
p4 = np.polyfit(x, y, 4)
xx = np.linspace(-0.2, 5.2, 400)
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(xx, 1.0 + 2.025*xx, 'k--', label='line through first and last points')
ax.plot(xx, np.polyval(p4, xx), color='tab:red', label='degree-4 polynomial')
ax.plot(x, y, 'ko', label='data')
ax.plot([5], [11.0], 'bs', ms=8, label='later measurement')
ax.set_xlabel('input $x$ (arbitrary units)')
ax.set_ylabel('output $y$ (arbitrary units)')
ax.legend(loc='upper left')
ax.grid(alpha=0.3)
plt.savefig('intro_memorize.pdf', bbox_inches='tight')
