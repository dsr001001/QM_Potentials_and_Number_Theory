import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
x = np.array([0, 1, 2, 3, 4.0])
y = np.array([1.0, 2.9, 5.2, 6.9, 9.1])
xx = np.linspace(-0.2, 5.3, 400)
p = np.polyfit(x, y, 4)
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(xx, 1.0 + 2.025 * xx, 'b--', label='line through first and last points')
ax.plot(xx, np.polyval(p, xx), 'r-', label='degree-4 polynomial')
ax.plot(x, y, 'ko', label='measured points')
ax.plot([5], [11.0], 'ks', ms=8, mfc='none', label='later measurement')
ax.set_xlabel('$x$ (arbitrary units)')
ax.set_ylabel('$y$ (arbitrary units)')
ax.legend()
ax.grid(alpha=0.3)
plt.savefig('intro_memorize.pdf', bbox_inches='tight')
