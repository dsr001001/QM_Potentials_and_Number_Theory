import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(6.5, 3))
def arrow(ax, start, vec, color, label):
    ax.annotate("", xy=(start[0]+vec[0], start[1]+vec[1]), xytext=start,
                arrowprops=dict(arrowstyle="->", color=color, lw=1.8))
    ax.text(start[0]+vec[0]/2, start[1]+vec[1]/2, label, color=color)
u = np.array([3, 1]); v = np.array([1, 2])
arrow(ax1, (0, 0), u, "C0", "u")
arrow(ax1, (0, 0), v, "C1", "v")
arrow(ax1, (0, 0), u+v, "k", "u+v")
ax1.plot([u[0], 4], [u[1], 3], "C1--", lw=0.8)
ax1.plot([v[0], 4], [v[1], 3], "C0--", lw=0.8)
ax1.set_xlim(-0.5, 4.5); ax1.set_ylim(-0.5, 3.5); ax1.set_aspect("equal")
ax1.set_xlabel("component 1 (dimensionless)"); ax1.set_ylabel("component 2 (dimensionless)")
ax1.set_title("addition")
a = np.array([3, 1]); b = np.array([1, 2]); p = (a @ b)/(a @ a)*a
arrow(ax2, (0, 0), a, "C0", "a")
arrow(ax2, (0, 0), b, "C1", "b")
arrow(ax2, (0, 0), p, "C2", "proj")
arrow(ax2, tuple(p), b-p, "C3", "residual")
ax2.set_xlim(-0.5, 3.5); ax2.set_ylim(-0.5, 2.5); ax2.set_aspect("equal")
ax2.set_xlabel("component 1 (dimensionless)")
ax2.set_title("projection")
plt.tight_layout()
plt.savefig("linear-algebra_vectors.pdf", bbox_inches="tight")
