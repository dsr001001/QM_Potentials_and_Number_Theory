import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
A = np.array([[2., 1.], [1., 2.]])
th = np.linspace(0, 2*np.pi, 400)
c = np.vstack([np.cos(th), np.sin(th)])
e = A @ c
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(c[0], c[1], 'k--', lw=1, label='unit circle')
ax.plot(e[0], e[1], 'k-', lw=1.5, label='image under $A$')
s = 1/np.sqrt(2)
def arrow(v, col, lw):
    ax.annotate('', xy=v, xytext=(0, 0), arrowprops=dict(arrowstyle='->', color=col, lw=lw))
arrow((3*s, 3*s), 'red', 2.5); arrow((s, s), 'darkred', 1.5)
arrow((s, -s), 'green', 2.5)
arrow((1, 0), 'gray', 1.5); arrow((2, 1), 'black', 1.5)
ax.text(3*s+0.05, 3*s+0.05, r'$Au_1=3u_1$', color='red')
ax.text(s+0.05, -s-0.25, r'$u_2=Au_2$', color='green')
ax.text(1.0, -0.3, r'$(1,0)$', color='gray')
ax.text(2.05, 1.0, r'$(2,1)$', color='black')
ax.set_aspect('equal')
ax.set_xlim(-3, 3); ax.set_ylim(-2.6, 2.6)
ax.axhline(0, color='0.85', lw=0.5); ax.axvline(0, color='0.85', lw=0.5)
ax.set_xlabel('first component (dimensionless)')
ax.set_ylabel('second component (dimensionless)')
ax.legend(loc='lower right', fontsize=8)
plt.savefig('eigen_stretch.pdf', bbox_inches='tight')
