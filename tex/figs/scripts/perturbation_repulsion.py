import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
v=0.5; g=np.linspace(-3,3,601); ex=np.sqrt(g**2+v**2)
fig,ax=plt.subplots(figsize=(6,4))
ax.plot(g,g,'k--',lw=1,label='uncoupled levels +g and -g')
ax.plot(g,-g,'k--',lw=1)
ax.plot(g,ex,'b-',lw=2,label='exact levels, v = 0.5')
ax.plot(g,-ex,'b-',lw=2)
ax.annotate('',xy=(0,v),xytext=(0,-v),arrowprops=dict(arrowstyle='<->',color='r'))
ax.text(0.1,0,'minimum gap 2|v| = 1',color='r',va='center')
ax.set_xlabel('diagonal parameter g (energy units)')
ax.set_ylabel('eigenvalue (energy units)')
ax.legend(loc='upper left')
plt.savefig('perturbation_repulsion.pdf',bbox_inches='tight')
