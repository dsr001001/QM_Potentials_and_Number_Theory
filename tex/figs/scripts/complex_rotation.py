import numpy as np, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
phi = np.linspace(0, 2 * np.pi, 400)
a1.plot(np.cos(phi), np.sin(phi), "k-", lw=0.8)
th = 0.9
z = np.exp(1j * th)
a1.annotate("", xy=(z.real, z.imag), xytext=(0, 0), arrowprops=dict(arrowstyle="->", color="C0", lw=1.8))
a1.plot([z.real, z.real], [0, z.imag], "C0:"); a1.plot([0, z.real], [z.imag, z.imag], "C0:")
a1.text(z.real / 2 - 0.1, -0.2, r"$\cos\theta$", color="C0")
a1.text(-0.6, z.imag, r"$\sin\theta$", color="C0")
w = 1.5 + 0.4j
w2 = w * np.exp(1j * np.pi / 3)
for v, c, lab in [(w, "C1", r"$w$"), (w2, "C3", r"$e^{i\pi/3}w$")]:
    a1.annotate("", xy=(v.real, v.imag), xytext=(0, 0), arrowprops=dict(arrowstyle="->", color=c, lw=1.5, ls="--"))
    a1.text(v.real + 0.05, v.imag + 0.05, lab, color=c)
a1.axhline(0, color="k", lw=0.5); a1.axvline(0, color="k", lw=0.5)
a1.set_aspect("equal"); a1.set_xlim(-1.3, 1.9); a1.set_ylim(-1.3, 1.9)
a1.set_xlabel("real part"); a1.set_ylabel("imaginary part")
thv = np.linspace(0, 4 * np.pi, 600)
a2.plot(thv, np.cos(thv), label=r"$\mathrm{Re}\,e^{i\theta}=\cos\theta$")
a2.plot(thv, np.sin(thv), "--", label=r"$\mathrm{Im}\,e^{i\theta}=\sin\theta$")
a2.set_xlabel(r"$\theta$ (rad)"); a2.set_ylabel("value (dimensionless)")
a2.legend(fontsize=7, loc="lower left")
plt.tight_layout()
plt.savefig("complex_rotation.pdf", bbox_inches="tight")
