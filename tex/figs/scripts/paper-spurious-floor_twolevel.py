import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
x = np.linspace(0, 1, 401)
exact = np.where(x < 0.5, 0.5*(1-np.sqrt(np.clip(1-4*x**2, 0, None))), 0.5)
ratio = np.where(x < 0.5, exact/np.where(x > 0, x, 1), 1.0)
ratio[0] = 0.0
weight = 1/(1+ratio**2)
fig, axs = plt.subplots(1, 2, figsize=(6.5,3))
axs[0].plot(x, exact, '-', label='exact')
axs[0].plot(x, x**2, '--', label='second order')
axs[0].axvline(0.5, color='gray', lw=0.8)
axs[0].set_xlabel(r'$x=a/\Delta$'); axs[0].set_ylabel(r'real shift of lower level ($\Delta$)')
axs[0].legend(fontsize=8)
axs[1].plot(x, weight, '-')
axs[1].axvline(0.5, color='gray', lw=0.8)
axs[1].set_xlabel(r'$x=a/\Delta$'); axs[1].set_ylabel('weight of state 1')
axs[1].set_ylim(0.4, 1.02)
plt.tight_layout()
plt.savefig('paper-spurious-floor_twolevel.pdf', bbox_inches='tight')
