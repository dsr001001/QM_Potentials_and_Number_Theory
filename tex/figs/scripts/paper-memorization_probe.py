import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
import qmnt
n = np.arange(1, 501)
s = qmnt.smooth_zeros(n)
f = -qmnt.Nfl(s, [2])
fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.5, 3))
a1.plot(n[299:], f[299:], '.-', ms=3, lw=0.7)
a1.axvspan(400.5, 500.5, color='0.85')
a1.set_xlabel('level index $n$')
a1.set_ylabel('target fluctuation (mean spacings)')
a2.plot(n, np.log2(s/(2*np.pi)), color='C1')
a2.set_xlabel('level index $n$')
a2.set_ylabel('levels per period of sin(t log 2)')
plt.tight_layout()
plt.savefig('paper-memorization_probe.pdf', bbox_inches='tight')
